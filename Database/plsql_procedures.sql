
-- 1. Add a subject
CREATE OR REPLACE PROCEDURE ADD_COLLEGE_SUBJECT (
    P_SUBJECT_NAME IN VARCHAR2,
    P_TEACHER_NAME IN VARCHAR2,
    P_STUDENT_GROUP IN VARCHAR2,
    P_CLASSROOM IN VARCHAR2,
    P_SESSIONS IN NUMBER,
    P_NEW_ID OUT NUMBER
)
AS
BEGIN
    IF TRIM(P_SUBJECT_NAME) IS NULL
       OR TRIM(P_TEACHER_NAME) IS NULL
       OR TRIM(P_STUDENT_GROUP) IS NULL
       OR TRIM(P_CLASSROOM) IS NULL THEN
        RAISE_APPLICATION_ERROR(-20001, 'All fields are required.');
    END IF;

    IF P_SESSIONS < 1 OR P_SESSIONS > 40
       OR P_SESSIONS <> TRUNC(P_SESSIONS) THEN
        RAISE_APPLICATION_ERROR(-20002, 'Sessions must be a whole number from 1 to 40.');
    END IF;

    INSERT INTO COLLEGE_SUBJECTS (
        SUBJECT_NAME, TEACHER_NAME, STUDENT_GROUP,
        CLASSROOM, SESSIONS_PER_WEEK
    )
    VALUES (
        TRIM(P_SUBJECT_NAME), TRIM(P_TEACHER_NAME),
        TRIM(P_STUDENT_GROUP), TRIM(P_CLASSROOM), P_SESSIONS
    )
    RETURNING ID INTO P_NEW_ID;
END;
/

-- 2. Delete a subject
CREATE OR REPLACE PROCEDURE DELETE_COLLEGE_SUBJECT (
    P_SUBJECT_ID IN NUMBER
)
AS
BEGIN
    DELETE FROM COLLEGE_SUBJECTS
    WHERE ID = P_SUBJECT_ID;

    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20003, 'Subject not found.');
    END IF;
END;
/

-- 3. Clear the timetable
CREATE OR REPLACE PROCEDURE CLEAR_COLLEGE_TIMETABLE
AS
BEGIN
    DELETE FROM COLLEGE_TIMETABLE;
END;
/

-- 4. Save a timetable entry after checking conflicts
CREATE OR REPLACE PROCEDURE SAVE_COLLEGE_TIMETABLE (
    P_SUBJECT_ID IN NUMBER,
    P_DAY_NAME IN VARCHAR2,
    P_PERIOD_NO IN NUMBER
)
AS
    V_TEACHER COLLEGE_SUBJECTS.TEACHER_NAME%TYPE;
    V_GROUP COLLEGE_SUBJECTS.STUDENT_GROUP%TYPE;
    V_CLASSROOM COLLEGE_SUBJECTS.CLASSROOM%TYPE;
    V_CONFLICTS NUMBER;
BEGIN
    IF P_DAY_NAME IS NULL OR P_DAY_NAME NOT IN (
        'Monday', 'Tuesday', 'Wednesday',
        'Thursday', 'Friday'
    ) OR P_PERIOD_NO IS NULL
       OR P_PERIOD_NO < 0 OR P_PERIOD_NO > 7
       OR P_PERIOD_NO <> TRUNC(P_PERIOD_NO) THEN
        RAISE_APPLICATION_ERROR(-20004, 'Invalid day or period.');
    END IF;

    SELECT TEACHER_NAME, STUDENT_GROUP, CLASSROOM
    INTO V_TEACHER, V_GROUP, V_CLASSROOM
    FROM COLLEGE_SUBJECTS
    WHERE ID = P_SUBJECT_ID;

    SELECT COUNT(*)
    INTO V_CONFLICTS
    FROM COLLEGE_TIMETABLE T
    JOIN COLLEGE_SUBJECTS S
      ON S.ID = T.SUBJECT_ID
    WHERE T.DAY_NAME = P_DAY_NAME
      AND T.PERIOD_NO = P_PERIOD_NO
      AND (
          UPPER(S.TEACHER_NAME) = UPPER(V_TEACHER)
          OR UPPER(S.STUDENT_GROUP) = UPPER(V_GROUP)
          OR UPPER(S.CLASSROOM) = UPPER(V_CLASSROOM)
      );

    IF V_CONFLICTS > 0 THEN
        RAISE_APPLICATION_ERROR(
            -20005,
            'Teacher, student group, or classroom conflict.'
        );
    END IF;

    INSERT INTO COLLEGE_TIMETABLE (
        SUBJECT_ID, DAY_NAME, PERIOD_NO
    )
    VALUES (
        P_SUBJECT_ID, P_DAY_NAME, P_PERIOD_NO
    );
END;


-- Table 1: Stores college subjects and their details

CREATE TABLE COLLEGE_SUBJECTS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SUBJECT_NAME VARCHAR2(100) NOT NULL,
    TEACHER_NAME VARCHAR2(100) NOT NULL,
    STUDENT_GROUP VARCHAR2(50) NOT NULL,
    CLASSROOM VARCHAR2(50) NOT NULL,
    SESSIONS_PER_WEEK NUMBER(2) NOT NULL,

    CONSTRAINT CHK_COLLEGE_SESSIONS
        CHECK (SESSIONS_PER_WEEK BETWEEN 1 AND 40)
);


-- Table 2: Stores the generated timetable

CREATE TABLE COLLEGE_TIMETABLE (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SUBJECT_ID NUMBER NOT NULL,
    DAY_NAME VARCHAR2(15) NOT NULL,
    PERIOD_NO NUMBER(1) NOT NULL,

    CONSTRAINT FK_COLLEGE_SUBJECT
        FOREIGN KEY (SUBJECT_ID)
        REFERENCES COLLEGE_SUBJECTS(ID)
        ON DELETE CASCADE,

    CONSTRAINT CHK_COLLEGE_DAY
        CHECK (
            DAY_NAME IN (
                'Monday', 'Tuesday', 'Wednesday',
                'Thursday', 'Friday'
            )
        ),

    CONSTRAINT CHK_COLLEGE_PERIOD
        CHECK (PERIOD_NO BETWEEN 0 AND 7)
);
